CREATE TABLE IF NOT EXISTS students (
  student_id text PRIMARY KEY CHECK (student_id ~ '^[0-9]{4}$'),
  first_name text NOT NULL,
  last_name text NOT NULL,
  major text NOT NULL
);

CREATE TABLE IF NOT EXISTS transcripts (
  student_id text PRIMARY KEY REFERENCES students(student_id) ON DELETE CASCADE,
  institution text NOT NULL,
  is_mock_data boolean NOT NULL DEFAULT false,
  semesters jsonb NOT NULL,
  summary jsonb NOT NULL
);

CREATE TABLE IF NOT EXISTS courses (
  course_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_code text NOT NULL,
  course_title text NOT NULL,
  section text NOT NULL,
  term text NOT NULL,
  UNIQUE (course_code, section, term)
);

CREATE TABLE IF NOT EXISTS enrollments (
  course_id integer NOT NULL REFERENCES courses(course_id) ON DELETE CASCADE,
  student_id text NOT NULL REFERENCES students(student_id) ON DELETE CASCADE,
  PRIMARY KEY (course_id, student_id)
);

CREATE TABLE IF NOT EXISTS course_grades (
  course_id integer NOT NULL,
  student_id text NOT NULL,
  grade text NOT NULL CHECK (grade IN ('A', 'B', 'C', 'D', 'F')),
  PRIMARY KEY (course_id, student_id),
  FOREIGN KEY (course_id, student_id)
    REFERENCES enrollments(course_id, student_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS faculty_schedule (
  schedule_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  meeting_type text NOT NULL CHECK (meeting_type IN ('class', 'office_hours')),
  course_id integer REFERENCES courses(course_id) ON DELETE CASCADE,
  day_of_week text NOT NULL CHECK (
    day_of_week IN ('Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday', 'Sunday')
  ),
  start_time time NOT NULL,
  end_time time NOT NULL,
  location text NOT NULL CHECK (length(trim(location)) > 0),
  CHECK (end_time > start_time),
  CHECK (
    (meeting_type = 'class' AND course_id IS NOT NULL)
    OR (meeting_type = 'office_hours' AND course_id IS NULL)
  )
);
