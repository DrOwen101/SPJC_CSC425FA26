BEGIN;

CREATE SCHEMA IF NOT EXISTS faculty_dashboard;

-- Faculty profiles are not login credentials. Authenticated accounts / roles
-- must be implemented and verified separately before exposing faculty endpoints.
CREATE TABLE IF NOT EXISTS faculty_dashboard.faculty (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(60) NOT NULL,
    last_name VARCHAR(60) NOT NULL,
    email VARCHAR(254) NOT NULL UNIQUE
);

-- Different sections of the same course may have different instructors.
CREATE TABLE IF NOT EXISTS faculty_dashboard.sections (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id INTEGER NOT NULL REFERENCES student_dashboard.courses(id),
    faculty_id INTEGER NOT NULL REFERENCES faculty_dashboard.faculty(id),
    semester VARCHAR(30) NOT NULL,
    section_code VARCHAR(20) NOT NULL,
    UNIQUE (course_id, semester, section_code)
);

-- A student may take multiple sections, but cannot enroll twice in one section.
CREATE TABLE IF NOT EXISTS faculty_dashboard.section_enrollments (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    section_id INTEGER NOT NULL REFERENCES faculty_dashboard.sections(id),
    student_id INTEGER NOT NULL REFERENCES student_dashboard.students(id),
    UNIQUE (section_id, student_id),
    UNIQUE (id, section_id)
);

-- One attendance status per enrolled student per class date.
CREATE TABLE IF NOT EXISTS faculty_dashboard.attendance (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    section_enrollment_id INTEGER NOT NULL REFERENCES faculty_dashboard.section_enrollments(id),
    class_date DATE NOT NULL,
    status VARCHAR(10) NOT NULL CHECK (status IN ('present', 'absent', 'excused')),
    UNIQUE (section_enrollment_id, class_date)
);

-- An assessment belongs to a section, with one positive maximum point value.
CREATE TABLE IF NOT EXISTS faculty_dashboard.assessments (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    section_id INTEGER NOT NULL REFERENCES faculty_dashboard.sections(id),
    assessment_name VARCHAR(150) NOT NULL,
    max_points NUMERIC(8,2) NOT NULL CHECK (max_points > 0),
    UNIQUE (section_id, assessment_name),
    UNIQUE (id, section_id)
);

-- A grade belongs to both an assessment and a section enrollment.
-- Repeating section_id allows composite foreign keys to enforce that
-- the enrollment and assessment belong to the same section.
CREATE TABLE IF NOT EXISTS faculty_dashboard.grades (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    section_id INTEGER NOT NULL REFERENCES faculty_dashboard.sections(id),
    section_enrollment_id INTEGER NOT NULL,
    assessment_id INTEGER NOT NULL,
    score NUMERIC(8,2) NOT NULL CHECK (score >= 0),
    UNIQUE (section_enrollment_id, assessment_id),
    FOREIGN KEY (section_enrollment_id, section_id)
        REFERENCES faculty_dashboard.section_enrollments(id, section_id),
    FOREIGN KEY (assessment_id, section_id)
        REFERENCES faculty_dashboard.assessments(id, section_id)
);

COMMIT;
