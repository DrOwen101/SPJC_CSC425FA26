
BEGIN;

-- Create a schema for account and role information.
CREATE SCHEMA IF NOT EXISTS auth;

-- Store the available user roles.
CREATE TABLE IF NOT EXISTS auth.roles (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(30) NOT NULL UNIQUE
);

-- Add the four supported roles.
INSERT INTO auth.roles (name)
VALUES
    ('student'),
    ('faculty'),
    ('staff'),
    ('administrator')
ON CONFLICT (name) DO NOTHING;

-- Store user accounts and their assigned roles.
CREATE TABLE IF NOT EXISTS auth.users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(254) NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    role_id INTEGER NOT NULL REFERENCES auth.roles(id),
    faculty_id INTEGER UNIQUE REFERENCES faculty_dashboard.faculty(id),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMIT;
